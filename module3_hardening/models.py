"""
Data models and schemas for Module 3 (FIDO2/Passkey Defense & Hardening Engine).
Defines structured classes for authentication profiles, hardening checklists,
and risk-based defense recommendations.
"""

from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import Any, Optional


class RiskLevel(str, Enum):
    """Categorized risk level matching the SOC alert hierarchy."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class AuthResistanceRating(str, Enum):
    """AiTM phishing resistance rating for authentication factors."""
    VULNERABLE = "VULNERABLE"                    # Relayed in real time by reverse proxies
    PARTIALLY_RESISTANT = "PARTIALLY_RESISTANT"  # Mitigates accidental prompt fatigue but still relayable
    PHISHING_RESISTANT = "PHISHING_RESISTANT"    # Cryptographically bound to origin; cannot be proxied


class AuthMethodType(str, Enum):
    """Recognized authentication methods across modern identity architectures."""
    PASSWORD_ONLY = "PASSWORD_ONLY"
    PASSWORD_SMS_OTP = "PASSWORD_SMS_OTP"
    PASSWORD_EMAIL_OTP = "PASSWORD_EMAIL_OTP"
    PASSWORD_TOTP_APP = "PASSWORD_TOTP_APP"
    CONVENTIONAL_PUSH = "CONVENTIONAL_PUSH"
    PUSH_NUMBER_MATCHING = "PUSH_NUMBER_MATCHING"
    FIDO2_SECURITY_KEY = "FIDO2_SECURITY_KEY"
    PASSKEY_DEVICE_BOUND = "PASSKEY_DEVICE_BOUND"
    PASSKEY_SYNCED = "PASSKEY_SYNCED"
    TOKEN_BINDING_DPOP = "TOKEN_BINDING_DPOP"
    CERTIFICATE_BASED_MTLS = "CERTIFICATE_BASED_MTLS"


class ChecklistPriority(str, Enum):
    """Priority level for hardening checklist items."""
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class ChecklistCategory(str, Enum):
    """Domain category for defensive hardening controls."""
    IDP_POLICY = "IDP_POLICY"
    WEBAUTHN_CONFIG = "WEBAUTHN_CONFIG"
    TOKEN_BINDING = "TOKEN_BINDING"
    CONDITIONAL_ACCESS = "CONDITIONAL_ACCESS"
    MONITORING_SOC = "MONITORING_SOC"
    EDGE_TRANSPORT = "EDGE_TRANSPORT"


@dataclass
class AuthMethodProfile:
    """Detailed profile of an authentication mechanism and its susceptibility to AiTM."""
    method_type: AuthMethodType
    display_name: str
    resistance_rating: AuthResistanceRating
    nist_aal_level: str  # AAL1, AAL2, AAL3
    mechanism_summary: str
    aitm_failure_mechanism: Optional[str]  # How reverse proxies bypass it
    aitm_resistance_explanation: str       # Why/how it resists or fails against AiTM
    origin_bound: bool
    requires_user_presence: bool
    requires_user_verification: bool
    recommended_action: str

    def to_dict(self) -> dict[str, Any]:
        res = asdict(self)
        res["method_type"] = self.method_type.value
        res["resistance_rating"] = self.resistance_rating.value
        return res


@dataclass
class HardeningChecklistItem:
    """Actionable machine-readable hardening checklist entry."""
    id: str
    category: ChecklistCategory
    title: str
    priority: ChecklistPriority
    summary: str
    implementation_steps: list[str]
    verification_method: str
    nist_reference: str
    cisa_guidance: str
    default_enabled: bool = False

    def to_dict(self) -> dict[str, Any]:
        res = asdict(self)
        res["category"] = self.category.value
        res["priority"] = self.priority.value
        return res


@dataclass
class DefenseRecommendation:
    """Actionable response recommendation produced for an alert event."""
    action_id: str
    risk_level: RiskLevel
    title: str
    action: str
    rationale: str
    urgency: str  # "IMMEDIATE", "WITHIN_1_HOUR", "ROUTINE"
    operator_guidance: str
    automated_remediation_suggested: bool

    def to_dict(self) -> dict[str, Any]:
        res = asdict(self)
        res["risk_level"] = self.risk_level.value
        return res


@dataclass
class HardeningPlan:
    """
    Complete defensive hardening package generated by Module 3 for a given detection event.
    Designed for seamless consumption by Module 4 (SOC Dashboard & User Training).
    """
    session_id: str
    input_risk_level: RiskLevel
    input_risk_score: float  # Normalized 0.0 to 1.0 or 0 to 100
    risk_score_percent: int  # Standardized 0-100 integer for SOC UI gauges
    primary_recommendations: list[str]  # Human-readable list matching Module 3 spec
    detailed_actions: list[DefenseRecommendation]
    signal_specific_remediations: list[str]
    checklist_highlights: list[HardeningChecklistItem]
    phishing_resistant_strategy: dict[str, Any]
    summary_banner: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "session_id": self.session_id,
            "risk_level": self.input_risk_level.value,
            "risk_score": self.input_risk_score,
            "risk_score_percent": self.risk_score_percent,
            "recommendations": self.primary_recommendations,
            "detailed_actions": [a.to_dict() for a in self.detailed_actions],
            "signal_specific_remediations": self.signal_specific_remediations,
            "checklist_highlights": [c.to_dict() for c in self.checklist_highlights],
            "phishing_resistant_strategy": self.phishing_resistant_strategy,
            "summary_banner": self.summary_banner,
        }
